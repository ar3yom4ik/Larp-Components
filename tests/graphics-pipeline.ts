import assert from 'node:assert/strict';
import * as THREE from 'three';
import { collectSceneTriangles } from 'three/addons/lighting/vxgi/VXGISceneCollector.js';
import { GiScene, GI_GEOMETRY_LAYER } from '../src/utils/giScene';
import { adaptivePixelRatio, preferLowGraphics } from '../src/utils/graphicsQuality';
import { defaultGfx, migrateGraphicsPreset, sanitizeGfx } from '../src/theme';
import { InstanceSlotCache } from '../src/utils/instanceSlots';
import { TemporalFrames } from '../src/utils/temporalFrames';
import { isWebGPURenderer } from '../src/utils/gpu';
import { configureVoxelGi, updateVoxelGi, type VoxelGi } from '../src/utils/vxgi';

assert.equal(preferLowGraphics({cores: 2, memoryGb: 16}), true);
assert.equal(preferLowGraphics({cores: 16, memoryGb: 4}), true);
assert.equal(preferLowGraphics({cores: 8, memoryGb: 8}), false);
assert.equal(preferLowGraphics({}), false, 'absent device hints are not evidence of a slow machine');
assert.deepEqual([0,1,2,3,4,10].map(level => adaptivePixelRatio(1, level)), [1,.85,.7,.6,.5,.5]);
assert.equal(adaptivePixelRatio(.35, 4), .35, 'adaptive quality never raises a low custom resolution');
assert.equal(defaultGfx('standard').shadowRadius, 1);
assert.equal(defaultGfx('standard').shadowExtent, 22);
assert.equal(defaultGfx('low').antialias, 'off');
assert.equal(defaultGfx('low').pixelRatio, .85);
assert.equal(defaultGfx('max').vxgiStrength, 1);
assert.equal(sanitizeGfx('standard', {vxgiStrength: 99}).vxgiStrength, 4);
const oldStandard = {...defaultGfx('standard'), shadowRadius:3, shadowExtent:26, contactOpacity:.5};
assert.equal(migrateGraphicsPreset('standard',oldStandard,4)?.shadowRadius,1, 'untouched older default gets sharper shadows');
assert.equal(migrateGraphicsPreset('standard',{...oldStandard,shadowRadius:7},4)?.shadowRadius,7, 'custom shadow controls are preserved');
assert.equal(migrateGraphicsPreset('standard',oldStandard,5)?.shadowRadius,3, 'already-current preferences are never migrated');
const oldLow = {...defaultGfx('low'),contactOpacity:.5,pixelRatio:1,antialias:'fxaa'};
assert.equal(migrateGraphicsPreset('low',oldLow,4)?.antialias, 'off');
assert.equal(migrateGraphicsPreset('low',{...oldLow,pixelRatio:1.5},4)?.pixelRatio,1.5, 'custom low preset is preserved');

const state = () => ({value:0});
const gi = {coneCount:state(),coneAngle:state(),normalOffset:state(),giIntensity:state(),aoIntensity:state(),aoDistance:state(),bounces:0,volume:{stepScale:state(),layers:new THREE.Layers()}} as unknown as VoxelGi;
configureVoxelGi(gi, 1.2, .8, .6);
assert.equal(gi.coneAngle.value, 40, 'Three.js cone aperture is in degrees');
assert.equal(gi.coneCount.value, 3);
assert.equal(gi.bounces, 1);
assert.equal(gi.volume.layers.mask, 1 << GI_GEOMETRY_LAYER);
assert.equal(gi.giIntensity.value, 1.2);
updateVoxelGi(gi, .3, 1.7, 1.4);
assert.deepEqual([gi.giIntensity.value,gi.aoIntensity.value,gi.aoDistance.value],[.3,1.7,1.4]);
assert.equal(isWebGPURenderer({isWebGPURenderer:true,backend:{isWebGPUBackend:true}}),true);
assert.equal(isWebGPURenderer({isWebGPURenderer:true,backend:{isWebGLBackend:true}}),false, 'renderer class alone does not prove compute support');
assert.equal(isWebGPURenderer(null),false);

const scene = new THREE.Scene();
const root = new THREE.Group(); root.userData.giGeometry = true; scene.add(root);
const nested = new THREE.Group(); nested.userData.giGeometry = true; root.add(nested);
const material = new THREE.MeshStandardMaterial({color:'#ccbb99'});
const physical = new THREE.Mesh(new THREE.BoxGeometry(2,2,2),material); physical.position.set(10,2,-3); nested.add(physical);
const originallyEnabled = new THREE.Mesh(new THREE.BoxGeometry(1,1,1),material); originallyEnabled.layers.enable(GI_GEOMETRY_LAYER); root.add(originallyEnabled);
const ground = new THREE.Mesh(new THREE.PlaneGeometry(240,240),material); ground.userData.giGround=true; root.add(ground);
const helper = new THREE.Mesh(new THREE.BoxGeometry(1,1,1),material); helper.position.x=1000; scene.add(helper);
const hidden = new THREE.Group(); hidden.visible=false; hidden.userData.giGeometry=true; const hiddenMesh=new THREE.Mesh(new THREE.BoxGeometry(),material); hidden.add(hiddenMesh); scene.add(hidden);
const instances = new THREE.InstancedMesh(new THREE.BoxGeometry(1,1,1),material,2);
instances.setMatrixAt(0,new THREE.Matrix4().makeTranslation(4,1,0)); instances.setMatrixAt(1,new THREE.Matrix4().makeTranslation(6,1,0)); root.add(instances);
const input = new GiScene(scene);
const bounds = input.prepare(true, '#557799').clone();
assert.ok(bounds.max.x < 20 && bounds.max.x > 10 && bounds.min.x > -10, `bounds exclude huge ground and editor helper: ${JSON.stringify(bounds)}`);
assert.equal(physical.layers.isEnabled(GI_GEOMETRY_LAYER),true);
assert.equal(ground.layers.isEnabled(GI_GEOMETRY_LAYER),false);
assert.equal(helper.layers.isEnabled(GI_GEOMETRY_LAYER),false);
assert.equal(hiddenMesh.layers.isEnabled(GI_GEOMETRY_LAYER),false);
const proxy = scene.getObjectByName('vxgi-ground-proxy') as THREE.Mesh;
assert.ok(proxy && proxy.layers.isEnabled(GI_GEOMETRY_LAYER));
assert.equal((proxy.material as THREE.MeshStandardMaterial).color.getHexString(),'557799');
const layers = new THREE.Layers(); layers.set(GI_GEOMETRY_LAYER);
const result = collectSceneTriangles(scene, { bounds, layers, exclude: new Set(), subVoxelSize:.2, maxEdge:8, minOpacity:.1 });
assert.ok(result.count > 0 && result.count < 50000, `bounded voxel inputs must collect physical triangles without subdividing a 240m floor: ${result.count}`);
input.prepare(false, '#112233');
assert.equal(scene.getObjectByName('vxgi-ground-proxy'),undefined, 'the Cornell room supplies its own floor');
let geometryDisposed=0, materialDisposed=0;
proxy.geometry.addEventListener('dispose',()=>geometryDisposed++);
(proxy.material as THREE.Material).addEventListener('dispose',()=>materialDisposed++);
input.dispose();
assert.equal(physical.layers.isEnabled(GI_GEOMETRY_LAYER),false, 'nested marked roots restore the original layer exactly once');
assert.equal(originallyEnabled.layers.isEnabled(GI_GEOMETRY_LAYER),true, 'a pre-existing layer is preserved');
assert.deepEqual([geometryDisposed,materialDisposed],[1,1]);

const camera = new THREE.PerspectiveCamera();
const frames = new TemporalFrames(3); frames.observe(camera);
assert.equal(frames.pending,true);
frames.rendered(); frames.rendered(); frames.rendered();
assert.equal(frames.pending,false, 'paused temporal accumulation eventually stops');
frames.observe(camera); assert.equal(frames.pending,false, 'a stationary camera stays idle');
camera.position.x=1; frames.observe(camera); assert.equal(frames.pending,true, 'camera moves restart convergence');
frames.rendered(); frames.rendered(); frames.rendered();
camera.fov=40; camera.updateProjectionMatrix(); frames.observe(camera); assert.equal(frames.pending,true, 'projection changes restart convergence');

const cache = new InstanceSlotCache(4);
const box = {x:1,y:2,z:3,yaw:0,tilt:0,ax:1,az:0,hx:1,hy:2,hz:3,color:0x123456};
cache.beginFrame();
assert.equal(cache.matrixChanged(2,box,1,undefined),true);
assert.equal(cache.matrixChanged(2,box,1,undefined),false);
assert.equal(cache.colorChanged(2,box.color,.15),true);
assert.equal(cache.colorChanged(2,box.color,.15),false);
assert.deepEqual([cache.matrixMin,cache.matrixMax,cache.colorMin,cache.colorMax],[2,2,2,2]);
cache.beginFrame();
assert.equal(cache.matrixChanged(2,{...box,x:2},1,undefined),true);
assert.equal(cache.matrixChanged(2,box,.5,undefined),true, 'fade changes the instance transform');
assert.equal(cache.matrixChanged(2,box,1,[0,.9,.1]),true, 'belt normal changes the instance transform');
assert.equal(cache.matrixChanged(2,box,1,[0,.9,.1]),false);
assert.equal(cache.colorChanged(2,box.color,.2),true, 'boost changes the instance colour');
assert.equal(cache.colorChanged(1,0,0),true, 'black is a valid colour');
assert.deepEqual([cache.colorMin,cache.colorMax],[1,2]);
console.log(`Graphics pipeline PASS: presets, real backend checks, bounded voxel scene (${result.count} triangles), cleanup, temporal convergence and instance caches`);
