const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TEST_URL || 'http://127.0.0.1:4173';
import fs from 'node:fs/promises';
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const errors = [];
function watch(page) { page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if(m.type()==='error') errors.push(m.text()); }); }
const desktop = await browser.newPage({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
watch(desktop);
await desktop.goto(base, {waitUntil:'networkidle'});
await desktop.waitForTimeout(4000);
await desktop.screenshot({path:'tests/artifacts/desktop.png'});
await desktop.getByRole('button', {name:'Program',exact:true}).last().click();
await desktop.waitForTimeout(500);
if(!await desktop.getByRole('button',{name:'Visual builder',exact:true}).isVisible()) throw new Error('Missing visual builder');
await desktop.screenshot({path:'tests/artifacts/program.png'});
const right=desktop.locator('aside').last();
await right.getByRole('button',{name:'Scene tree',exact:true}).click();
await right.getByRole('button',{name:'Feeder F-01',exact:true}).click();
await right.getByRole('button',{name:'Properties',exact:true}).click();
await right.getByRole('button',{name:'Spawn product',exact:true}).click();
await right.getByPlaceholder('Search name or tag...').fill('cookie food');
await right.getByRole('option',{name:/Chocolate chip cookie/}).click();
const selectedProduct = await desktop.evaluate(()=>window.__larp.items.find(i=>i.kind==='feeder').props.product);
if(selectedProduct!=='cookie') throw new Error('Search selection did not update feeder');
await desktop.screenshot({path:'tests/artifacts/products.png'});
await desktop.getByRole('button',{name:'FILE',exact:true}).click();
const dlPromise=desktop.waitForEvent('download');
await desktop.getByRole('button',{name:'Export copy (.txt)',exact:true}).click();
const download=await dlPromise; const file=await download.path();
const text=await fs.readFile(file,'utf8');
if(!download.suggestedFilename().endsWith('.txt') || !text.startsWith('LARP COMPONENTS 5.1')) throw new Error('TXT export failed');
await desktop.locator('input[type=file]').first().setInputFiles({name:'roundtrip.txt',mimeType:'text/plain',buffer:Buffer.from(text)});
await desktop.waitForTimeout(500);
await desktop.getByTitle('Language',{exact:true}).click();
await desktop.waitForTimeout(600);
if(!await right.getByRole('button',{name:'Свойства',exact:true}).isVisible()) throw new Error('Russian localization failed');
await desktop.screenshot({path:'tests/artifacts/russian.png'});
// Avoid starving the mobile page's software WebGL rendering with two live scenes.
await desktop.close();

const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1}); watch(phone);
await phone.goto(base,{waitUntil:'networkidle'}); await phone.waitForTimeout(2500);
if(!await phone.locator('.touch-workspace').count()) throw new Error('Phone not detected');
await phone.screenshot({path:'tests/artifacts/mobile.png'});
await phone.getByRole('navigation').getByRole('button',{name:'Program',exact:true}).click();
await phone.waitForTimeout(400);
await phone.screenshot({path:'tests/artifacts/mobile-program.png'});
if(!await phone.getByRole('button',{name:'Visual builder',exact:true}).isVisible()) throw new Error('Mobile program editor missing');
await phone.getByRole('button',{name:'Close sheet',exact:true}).click();
await phone.getByRole('button',{name:'AI Factory',exact:true}).click();
await phone.waitForTimeout(400);
if(!await phone.getByText('Factory parts', {exact:true}).isVisible()) throw new Error('Factory graph editor missing');
await phone.screenshot({path:'tests/artifacts/mobile-generator.png'});
await phone.getByRole('button',{name:'Build factory',exact:true}).click();
await phone.getByRole('button',{name:'Build factory',exact:true}).waitFor({state:'hidden'});
if(!await phone.evaluate(()=>window.__larp.items.some(i=>i.kind==='feeder'))) throw new Error('Factory graph did not build a feeder');
await phone.waitForTimeout(600);
await phone.getByTitle('Language',{exact:true}).click();
await phone.getByRole('navigation').getByRole('button',{name:'Проект',exact:true}).count().catch(()=>0);
await phone.screenshot({path:'tests/artifacts/mobile-russian.png'});
console.log('TXT exported bytes:',text.length);
console.log('Desktop, product search, workflow UI, Russian, TXT roundtrip, phone UI: PASS');
console.log('Runtime errors:',JSON.stringify(errors));
await browser.close();
if(errors.length) process.exitCode=1;
