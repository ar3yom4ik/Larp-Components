import { strict as assert } from 'node:assert';
import { zipSync, strToU8 } from 'fflate';
import { createProjectArchive, readProjectArchive } from '../src/utils/projectArchive';
import { parseProject, serializeProject } from '../src/utils/project';
import { makeItem } from '../src/data/library';

const asset = { id:'test', entry:'nested/model.obj', files:[{path:'nested/model.obj', dataUrl:'data:text/plain;base64,dmVydGV4'}, {path:'nested/tex.png', dataUrl:'data:image/png;base64,aGVsbG8='}] };
const imported = { asset, axis:'y' as const, units:'m' as const, materials:[], meshCount:1, triangleCount:1, rigged:false, animationNames:[] };
const first = makeItem('imported-model', [0,0,0], 0, {imported});
const project = { projectName:'Завод', layoutName:'Example', activeLayoutId:null, items:[first, {...first,id:'second'}] };
const text = serializeProject(project);
const zipped = createProjectArchive(text);
assert.ok(zipped.length < new TextEncoder().encode(text).length);
const decoded = readProjectArchive(zipped);
assert.equal(decoded,text);
const restored = parseProject(decoded);
assert.equal(restored.projectName,'Завод');
assert.deepEqual(restored.items[0].imported?.asset.files, asset.files);
assert.strictEqual(restored.items[0].imported?.asset, restored.items[1].imported?.asset);
assert.throws(()=>readProjectArchive(new Uint8Array([1,2,3])));
assert.throws(()=>readProjectArchive(zipSync({'../project.txt':strToU8(text)})));
assert.throws(()=>readProjectArchive(zipSync({'project.txt':strToU8(text),'other':strToU8('x')})));
const tampered = zipped.slice(); const end = tampered.length - 22;
const dv = new DataView(tampered.buffer); const dir = dv.getUint32(end + 16, true);
dv.setUint32(dir + 24, 180_000_001, true);
assert.throws(()=>readProjectArchive(tampered), /Unsupported/);
const badCrc = zipped.slice(); const cv = new DataView(badCrc.buffer); const cd = cv.getUint32(badCrc.length - 6, true); cv.setUint32(14, 42, true); cv.setUint32(cd + 16, 42, true);
assert.throws(()=>readProjectArchive(badCrc), /checksum/);
console.log('LCMX archive round-trip, asset deduplication and unsafe archive rejection OK');
