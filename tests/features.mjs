const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.TEST_URL||'http://127.0.0.1:4173';
await page.addInitScript(() => localStorage.setItem('larp-appearance', JSON.stringify({graphicsRevision:2, graphics:'standard', gfx:{shadows:false,contactShadows:false,ao:false,pixelRatio:1}})));
await page.goto(base,{waitUntil:'networkidle'});await page.waitForTimeout(1300);
const right=page.locator('aside').last();
await page.getByRole('button',{name:'Program',exact:true}).last().click();
await page.getByRole('button',{name:'Robot R-02',exact:true}).click();
await page.getByRole('spinbutton',{name:'Columns',exact:true}).fill('2');
await page.getByRole('spinbutton',{name:'Layers',exact:true}).fill('3');
await page.getByRole('button',{name:'Advanced options',exact:true}).click();
await page.getByLabel('Delay',{exact:true}).fill('1');
await page.getByRole('button',{name:'Link task',exact:true}).click();
await page.waitForTimeout(150);
let state=await page.evaluate(()=>{const s=window.__larp;const r=s.items.find(i=>i.name==='Robot R-02');const p=s.items.find(i=>i.kind==='crates');return{program:r.program,pallet:p.props};});
if(state.program.delay!==1||state.pallet.cols!==2||state.pallet.layers!==3||await page.evaluate(()=>[...window.__larp.robots.values()].find(r=>r.name==='Robot R-02').program.delay)!==1)throw new Error('Visual task or pallet options did not persist');
await right.getByRole('button',{name:'Scene tree',exact:true}).click();
await right.getByRole('button',{name:'Robot R-02',exact:true}).click();
await right.getByRole('button',{name:'Properties',exact:true}).click();
await right.getByRole('combobox',{name:'Gripper',exact:true}).selectOption('three-finger');
await page.waitForTimeout(250);

if(await page.evaluate(()=>[...window.__larp.robots.values()].find(r=>r.name==='Robot R-02').gripper)!=='three-finger')throw new Error('Gripper did not change');
async function select(name){await right.getByRole('button',{name:'Scene tree',exact:true}).click();await right.getByRole('button',{name,exact:true}).first().click();await right.getByRole('button',{name:'Properties',exact:true}).click();}
await select('Conveyor 2');
const previous=await page.evaluate(()=>window.__larp.items.find(i=>i.name==='Conveyor 2').points);
await right.getByRole('button',{name:'Reverse flow',exact:true}).click();
const reversed=await page.evaluate(()=>window.__larp.items.find(i=>i.name==='Conveyor 2').points);
if(JSON.stringify(previous.toReversed())!==JSON.stringify(reversed))throw new Error('Reverse failed');
await right.getByRole('button',{name:'Reverse flow',exact:true}).click();
await select('Cell Guarding');
const before=await page.evaluate(()=>window.__larp.items.find(i=>i.kind==='fence').points.length);
await right.getByRole('button',{name:'Add',exact:true}).click();
if(await page.evaluate(()=>window.__larp.items.find(i=>i.kind==='fence').points.length)!==before+1)throw new Error('Fence path edit failed');
await select('Operator A. Chen');
await right.getByRole('combobox',{name:'Task',exact:true}).selectOption('carry');
await right.getByRole('combobox',{name:'Head',exact:true}).selectOption('cap');
await page.waitForTimeout(150);
await right.getByRole('combobox',{name:'Face',exact:true}).selectOption('none');
await page.waitForTimeout(150);
const human=await page.evaluate(()=>window.__larp.items.find(i=>i.kind==='operator').props);
if(human.task!=='carry'||human.hat!=='cap'||human.glasses!==false)throw new Error('Human options did not persist');
await select('CNC M-01');
await right.getByRole('button',{name:'Output product',exact:true}).click();
await right.getByPlaceholder('Search name or tag...').fill('gear metal');
await right.getByRole('option',{name:/Steel gear/}).click();
await page.waitForTimeout(150);
if(await page.evaluate(()=>window.__larp.items.find(i=>i.kind==='cnc').props.outputProduct)!=='gear')throw new Error('Machine recipe option failed');
await page.getByRole('button',{name:'AI Factory',exact:true}).first().click();
const dialog=page.getByRole('dialog');
if(!await dialog.getByText('Factory parts', {exact:true}).isVisible()) throw new Error('Factory graph editor missing');
await dialog.getByRole('button',{name:'Build factory',exact:true}).click();
await dialog.waitFor({state:'hidden'});
await page.waitForTimeout(700);
console.log('Visual task binding, pallet pattern, grippers, reversal, fence points, hats/glasses, machine products, graph build: PASS');
console.log('Runtime errors:',JSON.stringify(errors));
await browser.close();if(errors.length)process.exitCode=1;
