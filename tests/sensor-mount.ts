import assert from 'node:assert/strict';
import {makeItem} from '../src/data/library';
import {Engine, BELT_TOP} from '../src/sim/engine';
import {mountedSensorPose, nearestSensorFraction, resolveMountedSensors} from '../src/utils/sensorMount';

const belt=makeItem('conveyor',[0,0,0],0,{points:[[-2,0],[2,0]],props:{width:1,active:false}});
const laser=makeItem('laser',[0,0,0],0,{props:{mountedTo:belt.id,mountPosition:.75}});
const mounted=resolveMountedSensors([belt,laser])[1];
assert.ok(Math.abs(mounted.position[0]-1)<.02); assert.ok(Math.abs(mounted.position[1]-BELT_TOP)<.001);
assert.ok(Math.abs(nearestSensorFraction(belt,[0,0,0])-.5)<.01,'dragging slides along the belt');
const moved={...belt,position:[2,1,3] as [number,number,number],rotation:90};
assert.deepEqual(resolveMountedSensors([moved,laser])[1].position,mountedSensorPose(moved,.75).position,'mount follows belt edits');
const e=new Engine();e.sync([belt,laser]); e.setRunning(true);
const glass=e.spawn('glass',1,BELT_TOP+.02,0);
for(let i=0;i<20;i++) e.step(1/60);
assert.equal(e.signalState.get(laser.id),false,'transparent workpiece passes beam');
glass.state='dead';
const carton=e.spawn('carton',1,BELT_TOP+.13,0);
for(let i=0;i<20;i++) e.step(1/60);
assert.equal(e.signalState.get(laser.id),true,'opaque part interrupts low mounted beam');
carton.state='dead';
for(let i=0;i<20;i++) e.step(1/60);
assert.equal(e.signalState.get(laser.id),false);
const cabinet=makeItem('cabinet',[1,0,0],0);
e.sync([belt,laser,cabinet]);for(let i=0;i<5;i++) e.step(1/60);
assert.equal(e.signalState.get(laser.id),true,'opaque scene equipment interrupts the beam');
const obstacleSensor=makeItem('sensor',[0,0,0],0,{props:{mountedTo:belt.id,mountPosition:.75,radius:.5}});
e.sync([belt,laser,obstacleSensor]);for(let i=0;i<5;i++)e.step(1/60);
assert.equal(e.signalState.get(laser.id),true,'other opaque sensors also interrupt the beam');
const proximity=makeItem('sensor',[0,0,0],0,{props:{mountedTo:belt.id,mountPosition:.75,radius:.5}});
const p=new Engine();p.sync([belt,proximity]);p.spawn('glass',1,BELT_TOP+.02,0);p.setRunning(true);for(let i=0;i<5;i++)p.step(1/60);
assert.equal(p.signalState.get(proximity.id),true,'proximity detects transparent workpieces');
console.log('laser: low conveyor mount, sliding, opacity, scene blockers and proximity OK');
