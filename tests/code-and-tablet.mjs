const { chromium }=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({args:['--enable-unsafe-swiftshader']});
const base=process.env.TEST_URL||'http://127.0.0.1:4173';
const page=await browser.newPage({viewport:{width:1440,height:960}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(() => localStorage.setItem('larp-appearance', JSON.stringify({graphicsRevision:2, graphics:'standard', gfx:{shadows:false,contactShadows:false,ao:false,pixelRatio:1}})));
await page.goto(base,{waitUntil:'networkidle'});await page.waitForTimeout(500);
await page.getByRole('button',{name:'Program',exact:true}).last().click();
await page.getByRole('button',{name:'Code',exact:true}).click();
await page.locator('textarea').fill('log("custom-code-ok"); await robot.wait(0.1);');
await page.getByRole('button',{name:'Apply code',exact:true}).click();
await page.waitForFunction(()=>window.__larp.logs.some(l=>l.text.includes('custom-code-ok')));
if(await page.evaluate(()=>[...window.__larp.robots.values()][0].program)!==undefined)throw new Error('Code mode did not replace visual task');
await page.locator('textarea').fill('while (true) {}');
await page.getByRole('button',{name:'Apply code',exact:true}).click();
await page.waitForFunction(()=>[...window.__larp.robots.values()][0].error?.includes('Loop ran too long'));
await page.getByTitle('Language',{exact:true}).click();
await page.getByTitle('API reference',{exact:true}).count().catch(()=>0);
await page.screenshot({path:'tests/artifacts/code-russian.png'});
const tablet=await browser.newPage({viewport:{width:1024,height:768},isMobile:true,hasTouch:true});tablet.on('pageerror',e=>errors.push(e.message));
await tablet.addInitScript(() => localStorage.setItem('larp-appearance', JSON.stringify({graphicsRevision:2, graphics:'standard', gfx:{shadows:false,contactShadows:false,ao:false,pixelRatio:1}})));
await tablet.goto(base,{waitUntil:'networkidle'});
if(!await tablet.locator('.touch-workspace').count())throw new Error('Touch tablet not detected');
await tablet.getByTitle('Language',{exact:true}).click();
await tablet.reload({waitUntil:'networkidle'});
if(!await tablet.getByRole('navigation').getByRole('button',{name:'Свойства',exact:true}).isVisible())throw new Error('Russian preference did not persist');
await tablet.getByRole('button',{name:'Проект',exact:true}).click();
await tablet.getByRole('navigation',{name:'Настройки'}).getByRole('button',{name:'Интерфейс и цвета',exact:true}).click();
await tablet.getByRole('button',{name:'Компьютер',exact:true}).click();
if(await tablet.locator('.touch-workspace').count())throw new Error('Interface override did not take effect');
console.log('Custom code, loop guard, touch tablet detection, persistent Russian, desktop override: PASS');
console.log('Uncaught errors:',JSON.stringify(errors));await browser.close();if(errors.length)process.exitCode=1;
