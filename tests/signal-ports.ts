import { strict as assert } from 'node:assert';
import { makeItem } from '../src/data/library';
import { canSignalInput, canSignalOutput } from '../src/utils/signalPorts';
import { Engine } from '../src/sim/engine';
import { serializeProject, parseProject } from '../src/utils/project';
import { createProjectArchive, readProjectArchive } from '../src/utils/projectArchive';
const a=makeItem('button',[-2,0,0],0,{name:'Button A'});
const b=makeItem('sensor',[0,0,0],0,{name:'Sensor B'});
const robot=makeItem('robot',[2,0,0],0,{name:'Robot'});
const plc=makeItem('plc',[4,0,0],0,{name:'PLC'});
assert.ok(canSignalOutput(a) && canSignalOutput(b) && canSignalOutput(plc));
assert.ok(canSignalOutput(robot));
assert.ok(!canSignalOutput({...a,locked:true}) && !canSignalOutput({...a,visible:false}));
assert.ok(canSignalInput(robot,a.id) && canSignalInput(plc,a.id));
assert.ok(!canSignalInput(a,a.id) && !canSignalInput({...robot,visible:false},a.id));
const items=[{...a,props:{...a.props,connectedTo:robot.id}},{...b,props:{...b.props,connectedTo:robot.id}},robot,plc];
const text=serializeProject({projectName:'Signals',layoutName:'Test',activeLayoutId:null,items});
const project=parseProject(readProjectArchive(createProjectArchive(text)));
assert.equal(project.items[0].props.connectedTo,robot.id);
assert.equal(project.items[1].props.connectedTo,robot.id);
const sim=new Engine();sim.sync(project.items);sim.setRunning(true);sim.setButton(a.id,true);sim.step(1/60);
assert.equal(sim.signalFor(robot.id),true,'button should signal robot');
sim.setButton(a.id,false);sim.spawn('carton',0,0.9,0);sim.step(1/60);
assert.equal(sim.signalFor(robot.id),true,'sensor should signal same target');
const disconnected=project.items.map(item=>item.id===a.id||item.id===b.id?{...item,props:{...item.props,connectedTo:''}}:item);
sim.sync(disconnected);sim.step(1/60);assert.equal(sim.signalFor(robot.id),false);
console.log('signal port eligibility, shared targets, live signals and project persistence OK');
