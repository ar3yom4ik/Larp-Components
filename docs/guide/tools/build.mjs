#!/usr/bin/env node
/* Concatenate the ESM sources into one classic (non-module) script bundle.
   Classic scripts load without CORS, so the site also works inside sandboxed
   iframes (opaque origin) and straight from the filesystem.
   Usage: node tools/build.mjs   (run from docs/guide/) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const FILES = [
  'src/md.js',
  'src/content/00-orientation.js',
  'src/content/01-build.js',
  'src/content/02-diagnosis.js',
  'src/content/03-ppm.js',
  'src/content/04-mastering.js',
  'src/content/05-report.js',
  'src/content/06-sources.js',
  'src/content/index.js',
  'src/app.js',
];

function stripModule(src) {
  return src
    .replace(/^import\s+[^\n]*\n/gm, '')
    .replace(/^export\s+/gm, '');
}

const seen = new Map();
const chunks = [];
for (const f of FILES) {
  const src = stripModule(read(f));
  for (const m of src.matchAll(/^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    const name = m[1];
    if (seen.has(name)) {
      console.error(`COLLISION: top-level "${name}" in ${f} and ${seen.get(name)}`);
      process.exit(1);
    }
    seen.set(name, f);
  }
  chunks.push(`/* ---------- ${f} ---------- */\n${src}`);
}

const bundle =
  '/* Generated by tools/build.mjs from the sources in src/. Do not edit by hand. */\n' +
  '(function () {\n"use strict";\n' + chunks.join('\n') + '\n})();\n';

fs.mkdirSync(path.join(root, 'assets', 'js'), { recursive: true });
const out = path.join(root, 'assets', 'js', 'bundle.js');
fs.writeFileSync(out, bundle);
console.log('wrote', out, bundle.length, 'bytes;', seen.size, 'top-level bindings');
