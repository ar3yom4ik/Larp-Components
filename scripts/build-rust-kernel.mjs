// Rebuild the checked-in embedded WASM from Rust. Requires Cargo and the
// wasm32-unknown-unknown target. The app's ordinary build needs no Rust install.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = path.join(root, 'rust/larp-kernel/Cargo.toml');
execFileSync('cargo', ['build', '--manifest-path', manifest, '--target', 'wasm32-unknown-unknown', '--release', '--offline'], {stdio:'inherit'});
const wasm = readFileSync(path.join(root, 'rust/larp-kernel/target/wasm32-unknown-unknown/release/larp_kernel.wasm'));
writeFileSync(path.join(root, 'src/sim/wasm/kernelBytes.ts'), `// Generated by npm run build:rust. Do not edit by hand.\nexport const KERNEL_BASE64 = '${wasm.toString('base64')}';\n`);
console.log(`Embedded Rust kernel: ${wasm.length} bytes`);
